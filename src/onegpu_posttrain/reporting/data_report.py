from __future__ import annotations

import json
from collections.abc import Iterable
from pathlib import Path
from statistics import mean
from typing import Any


def _percentile(values: list[float], q: float) -> float | None:
    if not values:
        return None
    xs = sorted(values)
    idx = (len(xs) - 1) * q
    lo = int(idx)
    hi = min(lo + 1, len(xs) - 1)
    frac = idx - lo
    return xs[lo] * (1 - frac) + xs[hi] * frac


def length_summary(values: Iterable[float]) -> dict[str, float | int | None]:
    xs = list(values)
    return {
        "count": len(xs),
        "min": min(xs) if xs else None,
        "max": max(xs) if xs else None,
        "mean": mean(xs) if xs else None,
        "p50": _percentile(xs, .50),
        "p90": _percentile(xs, .90),
        "p95": _percentile(xs, .95),
        "p99": _percentile(xs, .99),
    }


def write_report(path: str | Path, report: dict[str, Any]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True), encoding="utf-8")


def write_markdown_report(path: str | Path, title: str, report: dict[str, Any]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"# {title}", "", "> Generated by OneGPU-PostTrain. Values are build artifacts, not benchmark claims.", ""]
    _render_mapping(lines, report, level=2)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_processing_markdown_report(path: str | Path, report: dict[str, Any]) -> None:
    """Keep the processing trace readable without expanding a whole step dict into one line."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Data Processing Report", "", f"Build: `{report['build_id']}`", "",
             f"Protocol: `{report['processing_protocol']}`; stop reason: `{report['stop_reason']}`.", "",
             "Counts cover the processed source prefix. Quota exclusions are not quality rejections.", "",
             "| Step | Status | Input | Output | Rejected (input unit) | Not selected (input unit) |",
             "|---|---|---:|---:|---:|---:|"]
    for item in report["processing_steps"]:
        n_in, n_out = item["input_count"], item["output_count"]
        lines.append(f"| {item['order']}. {item['operation']} | {item['status']} | "
                     f"{n_in['value']} {n_in['unit']} | {n_out['value']} {n_out['unit']} | "
                     f"{item['rejected_count']} | {item['unselected_count']} |")
    lines.append("")
    for item in report["processing_steps"]:
        lines.extend([f"## {item['step_id']}", ""])
        for key in ("first_rejection_reasons", "unselected_reasons", "metrics_before", "metrics_after", "details", "limitations"):
            if item[key]:
                _render_mapping(lines, item[key], level=3, key=key)
    _render_mapping(lines, report["limitations"], level=2, key="Limitations")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _render_mapping(lines: list[str], value: Any, *, level: int, key: str | None = None) -> None:
    if key is not None:
        lines.append(f"{'#' * min(level, 6)} {key}")
        lines.append("")
    if isinstance(value, dict):
        scalar = {k: v for k, v in value.items() if not isinstance(v, (dict, list))}
        nested = {k: v for k, v in value.items() if isinstance(v, (dict, list))}
        if scalar:
            lines.extend(["| Metric | Value |", "|---|---:|"])
            for k, v in scalar.items():
                lines.append(f"| `{k}` | {v} |")
            lines.append("")
        for k, v in nested.items():
            _render_mapping(lines, v, level=level + 1, key=str(k))
    elif isinstance(value, list):
        if not value:
            lines.extend(["_empty_", ""])
        else:
            for item in value[:100]:
                lines.append(f"- {item}")
            if len(value) > 100:
                lines.append(f"- … {len(value) - 100} more")
            lines.append("")
    else:
        lines.extend([str(value), ""])
